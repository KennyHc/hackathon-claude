def log(msg: str, t0: float):
    print(f"[{time.time() - t0:6.1f}s] {msg}", flush=True)


def safe_symlink(target: str, link_path: str):
    """Create a symlink pointing to absolute target, replacing existing if present."""
    if os.path.islink(link_path) or os.path.exists(link_path):
        if os.path.islink(link_path) or os.path.isfile(link_path):
            os.unlink(link_path)
        else:
            shutil.rmtree(link_path)
    os.symlink(os.path.realpath(target), link_path)


def main():
    parser = argparse.ArgumentParser(description="Generate mock FINAL dataset for dry run")
    parser.add_argument("--out", default=DEFAULT_OUT, help="Output root directory")
    parser.add_argument("--data", default=DEFAULT_DATA, help="Base data directory (data/)")
    args = parser.parse_args()

    t0 = time.time()
    out_dir = os.path.abspath(args.out)
    data_dir = os.path.abspath(args.data)
    masters_dir = os.path.join(data_dir, "masters")
    live_dir = os.path.join(data_dir, "live")
    train_dir = os.path.join(data_dir, "train")

    log(f"Starting make_mock_final -> {out_dir}", t0)
    os.makedirs(out_dir, exist_ok=True)

    # 1. Base phase symlinks
    log("Creating root symlinks: masters, train, live...", t0)
    safe_symlink(masters_dir, os.path.join(out_dir, "masters"))
    safe_symlink(train_dir, os.path.join(out_dir, "train"))
    safe_symlink(live_dir, os.path.join(out_dir, "live"))

    # 2. Final directory setup
    final_dir = os.path.join(out_dir, "final")
    os.makedirs(final_dir, exist_ok=True)

    with open(os.path.join(final_dir, "README.txt"), "w") as fh:
        fh.write("Mock FINAL phase generated by integration/make_mock_final.py for pipeline dry runs.\n"
                 "Synthetic ZA01 subsidiary data based on data/live.\n")

    # Symlink every entry in live_dir except modified files and golden file
    skip_entries = {"bank_transactions.csv.gz", "ar_invoices.csv.gz", "open_items_at_start.csv.gz", "golden_allocations.csv.gz"}
    for entry in sorted(os.listdir(live_dir)):
        if entry in skip_entries:
            continue
        src = os.path.join(live_dir, entry)
        dst = os.path.join(final_dir, entry)
        safe_symlink(src, dst)

    # 3. masters_final
    log("Building final/masters_final (entities, bank_accounts, customers, fx_rates)...", t0)
    mf_dir = os.path.join(final_dir, "masters_final")
    os.makedirs(mf_dir, exist_ok=True)

    # 3a. entities.csv
    base_ent = pd.read_csv(os.path.join(masters_dir, "entities.csv"), dtype=str, keep_default_na=False)
    za_ent = pd.DataFrame([{
        "entity": "ZA01",
        "legal_name": "Kwena Water Solutions (Pty) Ltd",
        "country": "ZA",
        "functional_currency": "ZAR",
        "role": "commercial South Africa",
        "in_group_since": "2026-01-01",
    }])[list(base_ent.columns)]
    za_ent.to_csv(os.path.join(mf_dir, "entities.csv"), index=False)

    # 3b. bank_accounts.csv
    base_ba = pd.read_csv(os.path.join(masters_dir, "bank_accounts.csv"), dtype=str, keep_default_na=False)
    za_ba = pd.DataFrame([{
        "account_id": "ZA01-KWBK-ZAR",
        "entity": "ZA01",
        "bank": "KWBK",
        "bank_name": "Kwena Bank",
        "bic": "KWBKZAJJXXX",
        "currency": "ZAR",
        "iban": "",
        "account_number": "1234567890",
        "purpose": "Cobros / Pagos",
        "statement_format": "camt053",
        "statement_format_from_2025_10_01": "",
        "opened": "",
    }])[list(base_ba.columns)]
    za_ba.to_csv(os.path.join(mf_dir, "bank_accounts.csv"), index=False)

    # 3c. customers.csv
    base_cust = pd.read_csv(os.path.join(masters_dir, "customers.csv"), dtype=str, keep_default_na=False)
    new_customers = []
    for i in range(1, 41):
        cid = f"CZA01{i:06d}"
        cname = SA_COMPANIES[i - 1]
        new_customers.append({
            "customer_id": cid,
            "entity": "ZA01",
            "name": cname,
            "trade_name": "",
            "customer_type": "INSTALLER",
            "country": "ZA",
            "tax_id": f"4{i:09d}",
            "iban": "",
            "sepa_mandate_id": "",
            "payment_terms": "T30",
            "invoice_currency": "ZAR",
            "group_id": "",
            "parent_customer_id": "",
            "created": "2025-01-01",
            "blocked_since": "",
        })
    df_new_cust = pd.DataFrame(new_customers)
    renamed_3 = base_cust.iloc[:3].copy()
    renamed_3["name"] = renamed_3["name"] + " Holdings"
    mf_cust = pd.concat([df_new_cust, renamed_3], ignore_index=True)[list(base_cust.columns)]
    mf_cust.to_csv(os.path.join(mf_dir, "customers.csv"), index=False)

    # Seeded RNG
    rng = np.random.default_rng(7)

    # 3d. fx_rates.csv
    base_fx = pd.read_csv(os.path.join(masters_dir, "fx_rates.csv"), dtype=str, keep_default_na=False)
    usd_dates = base_fx[(base_fx["currency"] == "USD") & (base_fx["date"] >= "2025-07-01")]["date"].tolist()
    existing_fx_pairs = set(zip(base_fx["date"], base_fx["currency"]))
    fx_rows = []
    for d in usd_dates:
        if (d, "ZAR") not in existing_fx_pairs:
            noise = float(rng.normal(0, 0.05))
            fx_rows.append({
                "date": d,
                "currency": "ZAR",
                "units_per_eur": f"{19.5 + noise:.4f}",
                "source": "ECB",
            })
    mf_fx = pd.DataFrame(fx_rows, columns=list(base_fx.columns))
    mf_fx.to_csv(os.path.join(mf_dir, "fx_rates.csv"), index=False)

    # 4. Generate synthetic ZA01 items & bank transactions
    log("Generating synthetic ZA01 invoices and bank transactions...", t0)

    # Load existing live IDs to prevent collisions
    live_ar = pd.read_csv(os.path.join(live_dir, "ar_invoices.csv.gz"), dtype=str, keep_default_na=False)
    live_oi = pd.read_csv(os.path.join(live_dir, "open_items_at_start.csv.gz"), dtype=str, keep_default_na=False)
    live_bt = pd.read_csv(os.path.join(live_dir, "bank_transactions.csv.gz"), dtype=str, keep_default_na=False)

    existing_item_ids = set(live_ar["item_id"]) | set(live_oi["item_id"])
    existing_txn_ids = set(live_bt["bank_txn_id"])

    # 4a. 300 AR invoices in ar_invoices.csv.gz
    # item_id: ARI-2025-9<6 digits>
    ar_item_ids = []
    num = 1
    while len(ar_item_ids) < 300:
        cand = f"ARI-2025-9{num:06d}"
        if cand not in existing_item_ids:
            ar_item_ids.append(cand)
            existing_item_ids.add(cand)
        num += 1

    # Customer assignment for 300 invoices:
    # Ensure customers 0..19 each get at least 2 invoices so we can easily pair them for 20 multi-invoice bank lines.
    cust_indices = []
    for c in range(20):
        cust_indices.append(c)
        cust_indices.append(c)
    cust_indices.extend(rng.integers(0, 40, size=260).tolist())

    start_ar_date = datetime.date(2025, 7, 1)
    end_ar_date = datetime.date(2025, 11, 30)
    ar_date_span = (end_ar_date - start_ar_date).days

    ar_rows = []
    for i in range(300):
        c_idx = cust_indices[i]
        c_id = f"CZA01{c_idx + 1:06d}"
        c_name = SA_COMPANIES[c_idx]
        issue_d = start_ar_date + datetime.timedelta(days=int(rng.integers(0, ar_date_span + 1)))
        due_d = issue_d + datetime.timedelta(days=30)
        net = round(float(rng.uniform(1000.0, 80000.0)), 2)
        tax = round(net * 0.15, 2)
        tot = round(net + tax, 2)
        doc_num = f"KWI25-{i + 1:06d}"

        ar_rows.append({
            "item_id": ar_item_ids[i],
            "entity": "ZA01",
            "document_number": doc_num,
            "issue_date": issue_d.strftime("%Y-%m-%d"),
            "due_date": due_d.strftime("%Y-%m-%d"),
            "customer_id": c_id,
            "customer_name": c_name,
            "currency": "ZAR",
            "net_amount": f"{net:.2f}",
            "tax_amount": f"{tax:.2f}",
            "total_amount": f"{tot:.2f}",
            "payment_terms": "T30",
            "customer_po": "",
            "payment_method": "transfer",
            "_dt": issue_d,
            "_cust_idx": c_idx,
            "_tot": tot,
        })
    df_synth_ar = pd.DataFrame(ar_rows)

    # 4b. 50 open items in open_items_at_start.csv.gz
    # item_id: ARI-2025-8<6 digits>, issue_date 2025-05..06
    oi_item_ids = []
    num = 1
    while len(oi_item_ids) < 50:
        cand = f"ARI-2025-8{num:06d}"
        if cand not in existing_item_ids:
            oi_item_ids.append(cand)
            existing_item_ids.add(cand)
        num += 1

    start_oi_date = datetime.date(2025, 5, 1)
    end_oi_date = datetime.date(2025, 6, 30)
    oi_date_span = (end_oi_date - start_oi_date).days

    oi_rows = []
    for i in range(50):
        c_idx = int(rng.integers(0, 40))
        c_id = f"CZA01{c_idx + 1:06d}"
        issue_d = start_oi_date + datetime.timedelta(days=int(rng.integers(0, oi_date_span + 1)))
        due_d = issue_d + datetime.timedelta(days=30)
        tot = round(float(rng.uniform(1000.0, 80000.0)), 2)
        doc_num = f"KWI25-{800000 + i + 1:06d}"

        oi_rows.append({
            "item_id": oi_item_ids[i],
            "item_type": "ARI",
            "entity": "ZA01",
            "party_id": c_id,
            "document_number": doc_num,
            "issue_date": issue_d.strftime("%Y-%m-%d"),
            "due_date": due_d.strftime("%Y-%m-%d"),
            "currency": "ZAR",
            "total_amount": f"{tot:.2f}",
            "open_amount": f"{tot:.2f}",
        })
    df_synth_oi = pd.DataFrame(oi_rows)

    # 4c. 280 bank transactions in bank_transactions.csv.gz
    # 20 pay two invoices of the same customer (sum) -> invoices 0..39 (pairs (0,1), (2,3), ...)
    # 40 pay one invoice exactly with reference without prefix (`REF 25xxxxxx`) -> invoices 40..79
    # 200 pay one invoice exactly (`REF KWI25-xxxxxx`) -> invoices 80..279
    # 20 receipts that settle nothing (random amount, `EFT CREDIT UNKNOWN DEPOSIT`)
    max_rec_date = datetime.date(2025, 12, 31)

    raw_txns = []

    # 20 multi-invoice payments
    for k in range(20):
        inv1 = ar_rows[2 * k]
        inv2 = ar_rows[2 * k + 1]
        c_name = SA_COMPANIES[inv1["_cust_idx"]]
        tot = round(inv1["_tot"] + inv2["_tot"], 2)
        max_dt = max(inv1["_dt"], inv2["_dt"])
        offset = int(rng.integers(5, 41))
        b_dt = min(max_dt + datetime.timedelta(days=offset), max_rec_date)

        raw_txns.append({
            "b_dt": b_dt,
            "amount": f"{tot:.2f}",
            "text": f"EFT CREDIT {c_name.upper()} REF {inv1['document_number']} {inv2['document_number']}",
            "counterparty_name": c_name,
            "remittance_info": f"{inv1['document_number']} {inv2['document_number']}",
            "allocations": [
                (inv1["item_id"], inv1["total_amount"], "", ""),
                (inv2["item_id"], inv2["total_amount"], "", ""),
            ],
        })

    # 40 payments without prefix
    for i in range(40):
        inv = ar_rows[40 + i]
        c_name = SA_COMPANIES[inv["_cust_idx"]]
        tot = inv["_tot"]
        offset = int(rng.integers(5, 41))
        b_dt = min(inv["_dt"] + datetime.timedelta(days=offset), max_rec_date)
        digits_ref = "25" + inv["document_number"].split("-")[1]

        raw_txns.append({
            "b_dt": b_dt,
            "amount": f"{tot:.2f}",
            "text": f"EFT CREDIT {c_name.upper()} REF {digits_ref}",
            "counterparty_name": c_name,
            "remittance_info": digits_ref,
            "allocations": [
                (inv["item_id"], inv["total_amount"], "", ""),
            ],
        })

    # 200 exact payments
    for i in range(200):
        inv = ar_rows[80 + i]
        c_name = SA_COMPANIES[inv["_cust_idx"]]
        tot = inv["_tot"]
        offset = int(rng.integers(5, 41))
        b_dt = min(inv["_dt"] + datetime.timedelta(days=offset), max_rec_date)

        raw_txns.append({
            "b_dt": b_dt,
            "amount": f"{tot:.2f}",
            "text": f"EFT CREDIT {c_name.upper()} REF {inv['document_number']}",
            "counterparty_name": c_name,
            "remittance_info": inv["document_number"],
            "allocations": [
                (inv["item_id"], inv["total_amount"], "", ""),
            ],
        })

    # 20 unknown receipts
    start_unk_date = datetime.date(2025, 7, 1)
    unk_span = (max_rec_date - start_unk_date).days
    for i in range(20):
        tot = round(float(rng.uniform(500.0, 50000.0)), 2)
        offset = int(rng.integers(0, unk_span + 1))
        b_dt = start_unk_date + datetime.timedelta(days=offset)

        raw_txns.append({
            "b_dt": b_dt,
            "amount": f"{tot:.2f}",
            "text": "EFT CREDIT UNKNOWN DEPOSIT",
            "counterparty_name": "",
            "remittance_info": "",
            "allocations": [
                ("", "", "UNIDENTIFIED", "UNIDENTIFIED"),
            ],
        })

    # Sort the 280 transactions by booking date
    raw_txns.sort(key=lambda x: x["b_dt"])

    # Generate non-colliding bank_txn_ids
    bt_ids = []
    num = 1
    while len(bt_ids) < 280:
        cand = f"BT-2026-9{num:06d}"
        if cand not in existing_txn_ids:
            bt_ids.append(cand)
            existing_txn_ids.add(cand)
        num += 1

    final_txns = []
    expected_rows = []

    for idx, txn in enumerate(raw_txns):
        tid = bt_ids[idx]
        b_date_str = txn["b_dt"].strftime("%Y-%m-%d")
        yyyymm = txn["b_dt"].strftime("%Y%m")

        final_txns.append({
            "bank_txn_id": tid,
            "account_id": "ZA01-KWBK-ZAR",
            "entity": "ZA01",
            "bank": "KWBK",
            "statement_format": "camt053",
            "statement_file": f"final/bank_statements/ZA01-KWBK-ZAR/ZA01-KWBK-ZAR_{yyyymm}.xml",
            "booking_date": b_date_str,
            "value_date": b_date_str,
            "amount": txn["amount"],
            "currency": "ZAR",
            "bank_code": "PMNT/RCDT/ESCT",
            "bank_subcode": "",
            "ref1": f"KWBK{txn['b_dt'].strftime('%y%m%d')}{idx + 1:07d}",
            "ref2": "",
            "text": txn["text"],
            "counterparty_name": txn["counterparty_name"],
            "counterparty_account": "",
            "end_to_end_id": "NOTPROVIDED",
            "remittance_info": txn["remittance_info"],
            "orig_amount": "",
            "orig_currency": "",
        })

        for item_id, amt, cat, exc in txn["allocations"]:
            expected_rows.append({
                "bank_txn_id": tid,
                "item_id": item_id,
                "amount": amt,
                "category": cat,
                "exception": exc,
            })

    df_synth_bt = pd.DataFrame(final_txns)
    df_expected = pd.DataFrame(expected_rows, columns=["bank_txn_id", "item_id", "amount", "category", "exception"])

    # Write za01_expected.csv
    expected_path = os.path.join(final_dir, "za01_expected.csv")
    df_expected.to_csv(expected_path, index=False)

    # 5. Combine with live files and write gzip CSVs
    log("Combining with live files and writing compressed outputs...", t0)

    # 5a. bank_transactions.csv.gz
    full_bt = pd.concat([live_bt, df_synth_bt], ignore_index=True)[list(live_bt.columns)]
    full_bt.to_csv(os.path.join(final_dir, "bank_transactions.csv.gz"), index=False, compression="gzip")

    # 5b. ar_invoices.csv.gz
    clean_synth_ar = df_synth_ar[list(live_ar.columns)]
    full_ar = pd.concat([live_ar, clean_synth_ar], ignore_index=True)[list(live_ar.columns)]
    full_ar.to_csv(os.path.join(final_dir, "ar_invoices.csv.gz"), index=False, compression="gzip")

    # 5c. open_items_at_start.csv.gz
    full_oi = pd.concat([live_oi, df_synth_oi], ignore_index=True)[list(live_oi.columns)]
    full_oi.to_csv(os.path.join(final_dir, "open_items_at_start.csv.gz"), index=False, compression="gzip")

    total_time = time.time() - t0
    log(f"All done in {total_time:.1f}s -> {out_dir}", t0)
    print(f"Summary: bank_txns={len(full_bt):,} (+280), ar={len(full_ar):,} (+300), oi={len(full_oi):,} (+50), expected={len(df_expected):,}")


if __name__ == "__main__":
    main()
